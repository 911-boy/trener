// Порция → запись: { n, k, p, f, c }
function foodItem(f, count, grams, ml) {
  const g = grams != null ? grams : f.ug * count;
  const label = grams != null ? `${f.name}, ${Math.round(grams)} ${ml ? 'мл' : 'г'}` : `${f.name} × ${Math.round(count * 10) / 10}${f.u ? ' ' + f.u : ''}`;
  const m = x => Math.round(x * g / 100 * 10) / 10;
  return { n: label, k: Math.round(f.k * g / 100), p: m(f.p), f: m(f.f), c: m(f.c) };
}
